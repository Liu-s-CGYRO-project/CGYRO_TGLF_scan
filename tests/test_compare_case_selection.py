"""Exercise radius/isotope callbacks without importing a solver or a Tk app."""
from pathlib import Path
from contextlib import nullcontext
import sys
import unittest

LIB = Path(__file__).resolve().parents[1] / 'CGYRO_TGLF_scan/LIB'
sys.path.insert(0, str(LIB))
import OMFITlib_compare_state as state
import OMFITlib_compare_cases as cases_module
modules = {'cases': cases_module}


class FakeUI:
    """Resolve real widget bindings and retain callbacks for simulated clicks."""
    def __init__(self, root):
        self.root, self.events = root, []

    def same_row(self):
        return nullcontext()

    def __getattr__(self, kind):
        def call(*args, **kwargs):
            if kind == 'CheckBox':
                # These paths are generated by the selector, never external code.
                assert isinstance(eval(args[0], {'root': self.root}), bool)
            self.events.append(('', kind, args, kwargs))
        return call


class CaseSelectionTest(unittest.TestCase):
    def test_single_isotope_radii_need_no_second_selection(self):
        cases = ['nr={}__rho={}__ion=BASE'.format(i, rho)
                 for i, rho in enumerate((.5, .5875, .675, .7625, .85), 1)]
        selector = {'cgyro_radius_selected': [case.rsplit('__ion=', 1)[0] for case in cases]}
        root = {'selector': selector}
        ui = FakeUI(root)
        app = modules['cases'].CaseSelection(root, ui)
        app._select_cgyro_cases(selector, lambda *keys: state.dict_path("root['selector']", *keys), cases)
        self.assertEqual(selector['nr_selected'], cases)
        self.assertFalse(any(kind == 'CheckBox' and args[1] == '原始'
                             for _, kind, args, _ in ui.events))

    def test_radius_bulk_selection_includes_single_case_and_clears_it(self):
        cases = ['nr=1__rho=0.5__ion=BASE', 'nr=2__rho=0.6__ion=D']
        root = {'selector': {}}
        selector = root['selector']
        ui = FakeUI(root)
        app = modules['cases'].CaseSelection(root, ui)
        path = lambda *keys: state.dict_path("root['selector']", *keys)
        def render():
            ui.events.clear()
            app._select_cgyro_cases(selector, path, cases, 'nr_CGYRO')
        def click(label):
            next(args[1] for _, kind, args, _ in ui.events
                 if kind == 'Button' and args[0] == label)()
            render()
        render()
        self.assertEqual(selector['nr_CGYRO'], [])
        click('全选半径')
        self.assertEqual(selector['nr_CGYRO'], cases)
        click('清空半径')
        self.assertEqual(selector['nr_CGYRO'], [])
        self.assertFalse(any(selector['nr_flag'].values()))

    def test_isotope_bulk_selection_preserves_radius_scope_and_clear(self):
        cases = ['nr={}__rho={}__ion={}'.format(i, rho, ion)
                 for i, rho in ((1, .5), (2, .6)) for ion in ('H', 'D', 'T')]
        cases.append('nr=3__rho=0.7__ion=BASE')
        root = {'selector': {'cgyro_radius_selected': ['nr=1__rho=0.5', 'nr=3__rho=0.7'],
                             'nr_selected': [cases[0]]}}
        selector = root['selector']
        ui = FakeUI(root)
        app = modules['cases'].CaseSelection(root, ui)
        path = lambda *keys: state.dict_path("root['selector']", *keys)
        def render():
            ui.events.clear()
            app._select_cgyro_cases(selector, path, cases)
        def click(label):
            next(args[1] for _, kind, args, _ in ui.events
                 if kind == 'Button' and args[0] == label)()
            render()
        render()
        self.assertEqual(selector['nr_selected'], [cases[0], cases[-1]])
        click('全选离子')
        self.assertEqual(selector['nr_selected'], cases[:3] + cases[-1:])
        click('清空离子')
        self.assertEqual(selector['nr_selected'], cases[-1:])
        render()
        self.assertEqual(selector['nr_selected'], cases[-1:])
        self.assertEqual(selector['cgyro_radius_selected'], ['nr=1__rho=0.5', 'nr=3__rho=0.7'])


if __name__ == '__main__':
    unittest.main()
