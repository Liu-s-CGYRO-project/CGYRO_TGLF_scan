SCALE_BASES = {'GAMMA_E_SCALE': 'GAMMA_E', 'GAMMA_P_SCALE': 'GAMMA_P', 'MACH_SCALE': 'MACH'}


def parameter_help(name, spec=None):
    """Return factual help; unknown extension keys are not assigned meanings."""
    name = str(name)
    spec = field_spec(name) if spec is None else spec
    entry = PARAMETER_HELP.get(name, None)
    if entry is None and name in SCALE_BASES:
        base = SCALE_BASES[name]
        entry = ('有限实数；1 为原值，0 为关闭该贡献。', '将实验剖面生成的 ' + base + ' 乘以该因子。',
                 '无量纲倍率。', '仅用于 PROFILE_MODEL=2；局部输入直接设置 ' + base + '。')
    if entry is None:
        species = re.fullmatch(r'(DLNNDR_SCALE|DLNTDR_SCALE|SDLNNDR|SDLNTDR|DLNNDR|DLNTDR|MASS|DENS|TEMP|Z)_([1-9][0-9]*|AE)', name)
        if species:
            entry = SPECIES_HELP[species.group(1)]
    if entry is None:
        shape = re.fullmatch(r'SHAPE_(S_)?(COS[0-6]|SIN[3-6])', name)
        if shape:
            entry = ('有限实数，可带正负号。', '磁面形状 Fourier / MXH 谐波' +
                     ('的径向剪切系数。' if shape.group(1) else '系数。'), '无量纲几何系数。',
                     '按所用几何模型的定义填写；不是粒子参数。COS0、COS1 分别关联倾斜和椭圆偏形，高阶项描述更细的磁面形状。')
    if entry is None:
        kind = '整数' if spec.get('kind', 'float') == 'int' else '实数'
        allowed = ('正' if spec.get('positive', False) else '有限') + kind + '；只填写单个数值。'
        origin = 'CGYRO 原生输入参数' if spec.get('reference', None) is not None else '当前输入中的扩展参数'
        entry = (allowed, origin + '；本版未收录经核对的物理释义，不根据名称猜测。',
                 '请核对所用 CGYRO 版本。', '枚举值、归一化和启用条件以该版本原生输入定义为准。')
    allowed, meaning, units, conditions = entry
    return '\n'.join((name, '可输入：' + allowed, '含义：' + meaning, '单位 / 归一化：' + units,
        '适用条件：' + conditions, '',
        '常用归一化：a 为等离子体小半径；c_s=√(T_e/m_D)，m_D 为氘质量。',
        '官方参数说明：' + DOC_URL, '版本取值核对：' + CODE_URL))
