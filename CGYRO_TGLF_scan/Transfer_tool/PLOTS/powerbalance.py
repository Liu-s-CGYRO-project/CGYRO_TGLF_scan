# plot the turbulence and neoclassical transport flux and coefficient
tgyro=root['OUTPUTS']['TGYRO']
rho=tgyro['rho'][0]
figure(figsize=[16,12])
lw=2
fs2=24
ax1=subplot(231)
ax1.plot(rho[1:],tgyro['pflux_e_target'][0][1:],'-ko',linewidth=lw)
ax1.plot(rho[1:],tgyro['pflux_e_neo'][0][1:],'-bo',linewidth=lw)
ax1.plot(rho[1:],tgyro['pflux_e_target'][0][1:]-tgyro['pflux_e_neo'][0][1:],'-ro',linewidth=lw)
ax1.set_yscale('log')
title(r'$\Gamma_e(GB)$')
xticks(fontsize=fs2)
yticks(fontsize=fs2)
ax2=subplot(232)
ax2.plot(rho[1:],tgyro['eflux_e_target'][0][1:],'-ko',linewidth=lw)
ax2.plot(rho[1:],tgyro['eflux_e_neo'][0][1:],'-bo',linewidth=lw)
ax2.plot(rho[1:],tgyro['eflux_e_target'][0][1:]-tgyro['eflux_e_neo'][0][1:],'-ro',linewidth=lw)
ax2.set_yscale('log')
title('$Q_e(GB)$')
xticks(fontsize=fs2)
yticks(fontsize=fs2)
ax3=subplot(233)
ax3.plot(rho[1:],tgyro['eflux_i_target'][0][1:],'-ko',linewidth=lw,label='tur')
ax3.plot(rho[1:],tgyro['eflux_i1_neo'][0][1:]+tgyro['eflux_i2_neo'][0][1:],'-bo',linewidth=lw,label='neo')
ax3.plot(rho[1:],tgyro['eflux_i_target'][0][1:]-tgyro['eflux_i1_neo'][0][1:]-tgyro['eflux_i2_neo'][0][1:],'-ro',linewidth=lw,label='tur')
ax3.set_yscale('log')
title('$Q_i(GB)$')
xticks(fontsize=fs2)
yticks(fontsize=fs2)
legend(loc=0,fontsize=fs2).draggable(True)
fac=tgyro['Chi_GB'][0][1:]/tgyro['a/Lte'][0][1:]
fac2=tgyro['Chi_GB'][0][1:]/tgyro['a/Lti1'][0][1:]
subplot(234)
plot(rho[1:],fac*tgyro['pflux_e_target'][0][1:],'-ko',linewidth=lw,label='target')
plot(rho[1:],tgyro['pflux_e_neo'][0][1:]*fac,'-bo',linewidth=lw,label='neo')
plot(rho[1:],fac*(tgyro['pflux_e_target'][0][1:]-tgyro['pflux_e_neo'][0][1:]),'-ro',linewidth=lw,label='Tur')
title('$D(m^2/s)$')
xticks(fontsize=fs2)
yticks(fontsize=fs2)
xlabel('$\\rho$',fontsize=fs2)
subplot(235)
plot(rho[1:],fac*tgyro['eflux_e_target'][0][1:],'-ko',linewidth=lw)
plot(rho[1:],fac*tgyro['eflux_e_neo'][0][1:],'-bo',linewidth=lw)
plot(rho[1:],fac*(tgyro['eflux_e_target'][0][1:]-tgyro['eflux_e_neo'][0][1:]),'-ro',linewidth=lw)
title('$\chi_e(m^2/s)$')
xticks(fontsize=fs2)
yticks(fontsize=fs2)
xlabel('$\\rho$',fontsize=fs2)
subplot(236)
plot(rho[1:],fac2*tgyro['eflux_i_target'][0][1:],'-ko',linewidth=lw,label='target')
plot(rho[1:],fac2*(tgyro['eflux_i1_neo'][0][1:]+tgyro['eflux_i2_neo'][0][1:]),'-bo',linewidth=lw,label='neo')
plot(rho[1:],fac2*(tgyro['eflux_i_target'][0][1:]-tgyro['eflux_i1_neo'][0][1:]-tgyro['eflux_i2_neo'][0][1:]),'-ro',linewidth=lw,label='tur')
title('$\chi_i(m^2/s)$')
xticks(fontsize=fs2)
yticks(fontsize=fs2)
legend(loc=0,fontsize=fs2).draggable(True)
xlabel('$\\rho$',fontsize=fs2)
