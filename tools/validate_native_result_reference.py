"""Synthetic native serialization check; never open a user's project.

Run with a Linux Python containing real omfit_classes and pygacode:
    python tools/validate_native_result_reference.py

The real expression, tree saver/loader and CGYRO directory reader are used.
Standalone host adapters supply optional type names, scratch locations and a
reader for the scalar pickle created inside this fixture. This is not a full
OMFIT GUI session or a numerical solver/restart correctness check.
"""
import builtins
import copy
import hashlib
import json
import os
import pickle
from pathlib import Path
import sys
import tempfile
import types


def verify(reference_source):
    # Optional OMAS acceleration is irrelevant to serialization. Prevent its
    # import hook from compiling into the user's normal cache in this probe.
    sys.modules['omas.omas_cython'] = None
    library = Path(__file__).resolve().parents[1] / 'CGYRO_TGLF_scan/LIB'
    sys.path.insert(0, str(library))
    with tempfile.TemporaryDirectory(prefix='omfit-native-reference-') as directory:
        work = Path(directory)
        prior_cwd = os.getcwd()
        os.chdir(work)
        try:
            import omfit_classes.omfit_base as native
            from omfit_classes.omfit_gacode import OMFITcgyro
            import OMFITlib_cgyro_payload as payload_api
            helper = types.ModuleType('reference_under_test')
            exec(compile(reference_source, 'OMFITlib_cgyro_reference.py', 'exec'), helper.__dict__)
            native.OMFITcwd = str(work)
            native.OMFITtmpDir = str(work)
            native.OMFITcgyro = OMFITcgyro
            # Full-framework OMFITpickle is unavailable in standalone mode.
            # Only read the scalar pickle just generated by this test's saver.
            def fixture_pickle(filename):
                path = Path(filename).resolve()
                assert str(path).startswith(str(work.resolve()) + os.sep)
                with path.open('rb') as handle:
                    return pickle.load(handle)
            native.OMFITpickle = fixture_pickle
            # Standalone import omits optional MDSplus classes, although the
            # unchanged saver names them in an isinstance tuple. Host-only
            # placeholders are never instantiated or stored in this fixture.
            for name in ('OMFITmds', 'OMFITmdsValue', 'OMFITtoksearch', '_OMFITpython', 'OMFITdir'):
                if not hasattr(native, name):
                    setattr(native, name, builtins.type(name, (), {}))
            if OMFITcgyro not in native.OMFITtypes:
                native.OMFITtypes.append(OMFITcgyro)
            if 'OMFITcgyro' not in native.OMFITtypesStr:
                native.OMFITtypesStr.append('OMFITcgyro')
            tree = native.OMFITtree()
            tree._OMFITkeyName = 'OMFIT'
            tree['MainSettings'] = native.OMFIT['MainSettings']
            tree['scratch'] = native.OMFITtree()
            tree['CGYRO_scan'] = native.OMFITmodule()
            native.OMFIT = tree
            module = tree['CGYRO_scan']
            # A standalone host has no registered project LIB. The real native
            # importCode path is tested separately by validate_native_execution.
            module['LIB'] = {'OMFITlib_cgyro_payload': types.SimpleNamespace(importCode=lambda **kw: payload_api)}
            module['RUN_DB'] = native.OMFITtree()
            db = module['RUN_DB']
            db['__STORE__'] = native.OMFITtree()
            payload = work / 'synthetic-result'
            payload.mkdir()
            (payload / 'out.cgyro.info').write_text('Synthetic serialization fixture\n')
            (payload / 'bin.cgyro.restart').write_bytes(b'tiny synthetic checkpoint\n')
            digest = 'a' * 64
            owner = OMFITcgyro(str(payload), test_mode=True)
            owner.OMFITproperties['test_mode'] = True
            owner.modifyOriginal = False
            db['__STORE__'][digest] = owner
            db['Jet'] = native.OMFITtree()
            db['Jet']['0.1'] = helper.make_reference(digest, native.OMFITtree)
            ref = db['Jet']['0.1']
            expression = dict.__getitem__(ref, 'data')
            assert owner.dynaLoad, 'Reference construction read the result'
            assert helper.validate_reference(ref, digest) == digest
            assert owner.dynaLoad, 'Reference validation read the result'
            actual = expression._value_()
            assert actual is owner, (builtins.type(actual).__name__, expression.expression)
            assert 'out.cgyro.info' in list(expression.keys()), 'Native expression is not browsable'
            duplicate = copy.deepcopy(expression)
            assert duplicate.expression == expression.expression
            assert duplicate is not expression
            assert len(db['__STORE__']) == 1
            # Preserve copied metadata as a second branch: neither expression
            # may make the native saver deploy an additional physical result.
            db['Jet']['0.2'] = helper.make_reference(digest, native.OMFITtree)
            saved = work / 'saved'
            module.pop('LIB')  # Never persist the standalone host adapter.
            tree._save(str(saved), only="['CGYRO_scan']", quiet=True)
            index = (saved / 'OMFITsave.txt').read_text()
            rows = [line.split(' <-:-:-> ') for line in index.splitlines() if ' <-:-:-> ' in line]
            result_rows = [row for row in rows if row[1] == 'OMFITcgyro']
            expression_rows = [row for row in rows if row[1] == 'OMFITexpression' and "['data']" in row[0]]
            checkpoints = list(saved.rglob('bin.cgyro.restart'))
            assert len(result_rows) == len(checkpoints) == 1, (len(result_rows), len(checkpoints))
            assert len(expression_rows) == 2, expression_rows
            reopened = native.OMFITtree(str(saved / 'OMFITsave.txt'), quiet=True)
            reopened._OMFITkeyName = 'OMFIT'
            reopened['MainSettings'] = tree['MainSettings']
            reopened['scratch'] = native.OMFITtree()
            native.OMFIT = reopened
            reopened_module = reopened['CGYRO_scan']
            reopened_module['LIB'] = {'OMFITlib_cgyro_payload': types.SimpleNamespace(importCode=lambda **kw: payload_api)}
            reopened_ref = reopened_module['RUN_DB']['Jet']['0.1']
            reopened_owner = reopened_module['RUN_DB']['__STORE__'][digest]
            reopened_owner.test_mode = True  # This fixture deliberately has no solver arrays.
            helper.validate_reference(reopened_ref, digest)
            restored = dict.__getitem__(reopened_ref, 'data')
            assert restored._value_() is reopened_owner
            assert 'out.cgyro.info' in list(restored.keys())
            report = dict(source=native.__file__, python=sys.version.split()[0],
                          reference_sha256=hashlib.sha256(reference_source.encode()).hexdigest(),
                          native_result_rows=len(result_rows), native_expression_rows=len(expression_rows),
                          saved_checkpoints=len(checkpoints), construction_did_not_load=True,
                          native_expression_deepcopy=True, reopened_browsable=True)
            print('NATIVE_REFERENCE_PASS ' + json.dumps(report, sort_keys=True))
            return report
        finally:
            os.chdir(prior_cwd)


if __name__ == '__main__':
    source = (Path(sys.argv[1]) if len(sys.argv) > 1 else
              Path(__file__).resolve().parents[1] / 'CGYRO_TGLF_scan/LIB/OMFITlib_cgyro_reference.py')
    verify(source.read_text(encoding='utf-8'))
